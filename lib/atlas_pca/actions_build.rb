# frozen_string_literal: true

# `pca actions build|sign` as pure functions (native port of build.ts of the TypeScript reference @atlasauth/pca-actions): from defs to the
# unsigned schema, the pack, policy cards, ontology fragment, MCP tool map and generated TypeScript declarations, plus pack signing and
# the consistency check.
require_relative 'actions'
require_relative 'actions_derive'
require_relative 'actions_effective'
require_relative 'actions_lint'
require_relative 'agent'

module AtlasPca
  module ActionsBuild
    A = AtlasPca::Actions
    DR = AtlasPca::ActionsDerive
    E = AtlasPca::ActionsEffective
    MAX_PACK_DEFS = 4096
    PACK_SIGN_DOMAIN = "#{A::PACK_DIGEST_DOMAIN}\0".freeze
    IDENT_RE = /\A[A-Za-z_][A-Za-z0-9_]*\z/

    module_function

    def u16(xs) = xs.sort_by { |x| A.u16key(x) }

    # Every output of a build. Raises on a pack above the unsharded limit, a duplicate verb or a unit conflict (never a partial build).
    def build_artifacts(defs_in, cfg, reg, verifier = nil)
      defs = defs_in.sort_by { |d| A.u16key(d['verb']) }
      raise ArgumentError, "a pack above #{MAX_PACK_DEFS} defs must be sharded (#{defs.length} given)" if defs.length > MAX_PACK_DEFS

      (1...defs.length).each { |i| raise ArgumentError, "verb '#{defs[i]['verb']}' appears twice" if defs[i]['verb'] == defs[i - 1]['verb'] }
      raise A::ActionKitError.new('empty_pack', 'a pack has at least one def') if defs.empty?

      root = A.pack_root(defs.map { |d| A.def_digest(d) })
      schema = DR.to_schema_doc(defs, reg, { 'site' => cfg['site'], 'aud' => cfg['aud'], 'version' => cfg['version'], 'pack' => { 'ns' => cfg['ns'], 'version' => cfg['version'], 'root' => root } }, verifier)
      pack = { 'v' => 1, 'kind' => 'pca-action-pack', 'ns' => cfg['ns'], 'version' => cfg['version'], 'stability' => cfg['stability'], 'traits_digest' => A.traits_digest(reg),
               'roles_digest' => A.tables_digest, 'rules_digest' => ActionsLint.lint_rules_digest, 'root' => root, 'defs' => defs, 'prev' => nil, 'evolution' => [] }
      cards = defs.map { |d| DR.card_of(d, E.effective_with(d, reg, verifier), reg) }
      tools = {}
      defs.each do |d|
        mcp = (d['bindings'] || {})['mcp']
        tools[mcp['tool']] = { 'verb' => d['verb'], 'annotations' => DR.mcp_annotations_of(d, E.effective_with(d, reg, verifier)) } unless mcp.nil?
      end
      { 'schema' => schema, 'pack' => pack, 'cards' => cards, 'ontology' => DR.to_ontology(defs, reg, verifier), 'mcp' => { 'tools' => tools }, 'types' => generate_types(defs) }
    end

    # The ToolActionMap of the defs' MCP bindings: tool name and arguments to {verb, resource}, or nil.
    def tool_action_map_of(defs)
      m = {}
      defs.each do |d|
        mcp = (d['bindings'] || {})['mcp']
        m[mcp['tool']] = d unless mcp.nil?
      end
      lambda do |tool, args|
        d = m[tool]
        next nil if d.nil?

        r = DR.operation_of(d, { 'params' => args })
        r['ok'] ? { 'verb' => r['op']['verb'], 'resource' => r['op']['resource'] } : nil
      end
    end

    # ---- generated types ------------------------------------------------------------------------------------------

    def pascal(s) = s.split(/[._]/, -1).map { |x| "#{x[0, 1].upcase}#{x[1..]}" }.join

    def key(k) = IDENT_RE.match?(k) ? k : AtlasPca::Js.json(k)

    def ts_type(p)
      js = ->(vs) { vs.map { |v| AtlasPca::Js.json(v) }.join(' | ') }
      case p['type']
      when 'integer', 'duration' then 'number'
      when 'boolean' then 'boolean'
      when 'set' then "Array<#{js.call(p['values'] || []).then { |s| s.empty? ? 'string' : s }}>"
      when 'array' then p['items'] == 'integer' ? 'number[]' : 'string[]'
      else p['values'].nil? ? 'string' : js.call(p['values'])
      end
    end

    def render(n, indent)
      u16(n['kids'].keys).map do |k|
        c = n['kids'][k]
        if c.key?('leaf')
          "#{indent}#{key(k)}#{c['leaf']['required'] == false ? '?' : ''}: #{ts_type(c['leaf'])};"
        else
          "#{indent}#{key(k)}: {\n#{render(c, "#{indent}  ")}\n#{indent}};"
        end
      end.join("\n")
    end

    # TypeScript declarations for typed call sites: one params interface per verb, ActionParams and ActionVerb.
    def generate_types(defs)
      out = ['// Generated by `pca actions build`. Do not edit.', '']
      names = []
      defs.sort_by { |x| A.u16key(x['verb']) }.each do |d|
        root = { 'kids' => {} }
        u16(d['params'].keys).each do |name|
          n = root
          segs = name.split('.', -1)
          segs.each_with_index do |s, i|
            n['kids'][s] = { 'kids' => {} } unless n['kids'].key?(s)
            n = n['kids'][s]
            n['leaf'] = d['params'][name] if i == segs.length - 1
          end
        end
        iface = "#{pascal(d['verb'])}Params"
        names << "  #{AtlasPca::Js.json(d['verb'])}: #{iface};"
        out.push("export interface #{iface} {", render(root, '  '), '}', '')
      end
      out.push('export interface ActionParams {', *names, '}', '', 'export type ActionVerb = keyof ActionParams;', '')
      out.join("\n")
    end

    # ---- pack signing and consistency -----------------------------------------------------------------------------

    def pack_message(p) = PACK_SIGN_DOMAIN.b + AtlasPca.canon_bytes(p)

    # nil when the pack is internally consistent: every def valid and unique, the Merkle root and digests recomputed.
    def pack_consistency_error(p, reg)
      return 'the pack must be an object' unless p.is_a?(Hash)
      return 'not a pca-action-pack v1' if p['kind'] != 'pca-action-pack' || p['v'] != 1

      defs = p['defs']
      return 'defs must be a list within the unsharded limit' if !defs.is_a?(Array) || defs.length > MAX_PACK_DEFS

      seen = {}
      defs.each do |d|
        e = A.validate_def(d)
        return "def #{d.is_a?(Hash) ? (d.key?('verb') ? d['verb'] : '?') : '?'}: #{e}" if e
        return "verb '#{d['verb']}' is defined twice" if seen.key?(d['verb'])

        seen[d['verb']] = true
      end
      return 'the pack root does not match its defs' if p['root'] != A.pack_root(defs.map { |d| A.def_digest(d) })
      return 'traits_digest does not match the trait registry' if p['traits_digest'] != A.traits_digest(reg)

      nil
    rescue StandardError => e
      "malformed pack: #{e.message}"
    end

    # Sign a pack as the registry (Ed25519, 32-byte secret). Refuses an inconsistent pack.
    def sign_pack(pack, kid, secret, reg)
      bad = pack_consistency_error(pack, reg)
      raise ArgumentError, "signPack: #{bad}" if bad

      body = pack.reject { |k, _| k == 'sig' }
      body.merge('sig' => { 'alg' => 'ed25519', 'kid' => kid, 'value' => AtlasPca.b64e(AtlasPca::KeyPair.new(secret).sign(pack_message(body))) })
    end

    def pack_key_of(kid, secret) = { 'kid' => kid, 'alg' => 'ed25519', 'pk' => AtlasPca::KeyPair.new(secret).public }

    # Verify a signed pack against pinned registry keys: consistency, the key entry by kid, and the signature. Never raises.
    def verify_signed_pack(pack, keys, reg)
      bad = pack_consistency_error(pack, reg)
      return { 'ok' => false, 'reason' => bad } if bad

      sig = pack['sig']
      body = pack.reject { |k, _| k == 'sig' }
      return { 'ok' => false, 'reason' => 'missing or malformed signature' } if !sig.is_a?(Hash) || sig['alg'] != 'ed25519' || !sig['kid'].is_a?(String) || !sig['value'].is_a?(String)

      k = keys.find { |x| x['kid'] == sig['kid'] }
      return { 'ok' => false, 'reason' => "no registry key with kid '#{sig['kid']}'" } if k.nil?
      return { 'ok' => false, 'reason' => 'the registry key entry is malformed' } if k['alg'] != 'ed25519' || !k['pk'].is_a?(String) || AtlasPca.b64d(k['pk'], 32).nil?

      AtlasPca.verify_b64u(k['pk'], pack_message(body), sig['value']) ? { 'ok' => true } : { 'ok' => false, 'reason' => 'pack signature invalid' }
    rescue StandardError => e
      { 'ok' => false, 'reason' => "pack verification error: #{e.message}" }
    end
  end
end
