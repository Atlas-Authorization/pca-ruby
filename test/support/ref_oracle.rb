# frozen_string_literal: true

# Replay harness for the TS-generated package oracles (test-data/ref-<package>.json.gz). A case is {fn, name, args, out}:
# bytes are {"$bytes": b64url}; a reference throw is {"$throws": msg, code?} (the same code is required when present, else
# any refusal). Results compare as canonical JSON after normalization (an integral Float is an Integer: JS has one number
# type; a Symbol is its String). Each test_ref_*.rb maps fn -> the AtlasPca twin and calls Ref.run.
require_relative '../../lib/atlas_pca'
require 'zlib'
require 'json'
require 'base64'
require 'digest'

module Ref
  DATA = File.expand_path('../../test-data', __dir__)
  # the generator clock (epoch ms) of corpora committed before the header carried "clockMs"
  FALLBACK_CLOCK_MS = 1_800_000_000_000
  CLOCKS = {}

  module_function

  # {fn => [case, ...]} of test-data/ref-<name>.json.gz (a duplicate key keeps the last value, as JSON.parse).
  def load(name, seeds: true, path: nil)
    txt = Zlib::GzipReader.open(path || File.join(DATA, "ref-#{name}.json.gz"), &:read).force_encoding('UTF-8')
    # the JS view (-0 is -0.0, an integer beyond 2^53 a Float), without the wire-size cap: a corpus is a trusted local file
    d = AtlasPca::JsonParser.new(txt, true, true, json_text: true).parse_document
    raise 'case count mismatch' unless d['cases'].length == d['count']

    CLOCKS[name] = clock_of_header(d) unless path

    d = unseed(d) if seeds
    # long strings are stored once in the header's "blobs" table and appear as {"$blob": id}
    d = d.merge('cases' => resolve_blobs(d['cases'], d['blobs'])) if d['blobs'].is_a?(Hash)

    d['cases'].group_by { |c| c['fn'] }
  end

  # the frozen clock a corpus header records as "clockMs", else FALLBACK_CLOCK_MS
  def clock_of_header(header)
    v = header['clockMs']
    v.is_a?(Numeric) && v.to_f.finite? ? v : FALLBACK_CLOCK_MS
  end

  # the one clock accessor of the replays: the frozen clock of the corpus `name` (load it first)
  def clock_ms(name) = CLOCKS.fetch(name, FALLBACK_CLOCK_MS)

  # Oracle cases that carry private keys (not derived from a seed label) live in ref-<name>-gen.json.gz, generated by CI
  # (.github/scripts/gen-secret-corpus.sh) and never committed. nil when the file is absent (see need_gen).
  def gen_path(name) = File.join(ENV['PCA_SECRET_CORPUS_DIR'] || DATA, "ref-#{name}-gen.json.gz")
  def load_gen(name, **kw) = File.exist?(gen_path(name)) ? load(name, path: gen_path(name), **kw) : nil

  # A missing -gen corpus FAILS under CI (CI is "true"/"1"), else skips.
  def need_gen(test, name)
    msg = "ref-#{name}-gen.json.gz not found at #{gen_path(name)} (generate with .github/scripts/gen-secret-corpus.sh or set PCA_SECRET_CORPUS_DIR)"
    test.flunk msg if %w[true 1].include?(ENV['CI'])
    test.skip msg
  end

  def merge_cases(main, gen) = gen ? main.merge(gen) { |_, x, y| x + y } : main

  # every corpus fn is mapped; every mapped fn has cases once the -gen corpus is present
  def check_covered(test, all, gen, map_keys)
    test.assert_empty all.keys - map_keys
    test.assert_empty map_keys - all.keys if gen
  end

  # A corpus carries no private key material: {"$seed": label} (optionally "es256": true) stands for the key member the generator
  # derived from sha256("atlas-pca-conformance/" + label) (an ES256 scalar: the same digest with the top bit of byte 0 cleared).
  def seed_member(h)
    pre = "atlas-pca-conformance/#{h['$seed']}"
    if h['ed448']
      raw = Digest::SHA256.digest(pre).b + Digest::SHA256.digest("#{pre}/2").b[0, 25]
    elsif h['ec']
      # plain SHA-256 stretch, no bignum: P-384 -> 48 bytes (byte0 &= 0x7F), P-521 -> 66 bytes (byte0 &= 0x01)
      len, mask = h['ec'] == 'P-521' ? [66, 0x01] : [48, 0x7F]
      raw = (Digest::SHA256.digest(pre) + Digest::SHA256.digest("#{pre}/2") + Digest::SHA256.digest("#{pre}/3")).b[0, len]
      raw.setbyte(0, raw.getbyte(0) & mask)
    else
      raw = Digest::SHA256.digest(pre).b
      raw.setbyte(0, raw.getbyte(0) & 0x7F) if h['es256']
    end
    b64e(raw)
  end

  # {"$utf16": [code units]}: UTF-8 bytes of the string, a lone surrogate as its WTF-8 form (what the lane's JSON reader leaves)
  def wtf8(units)
    out = ''.b
    i = 0
    while i < units.length
      c = units[i]
      if c.between?(0xD800, 0xDBFF) && i + 1 < units.length && units[i + 1].between?(0xDC00, 0xDFFF)
        c = 0x10000 + ((c - 0xD800) << 10) + (units[i + 1] - 0xDC00)
        i += 1
      end
      out << (if c < 0x80 then [c].pack('C') elsif c < 0x800 then [0xC0 | (c >> 6), 0x80 | (c & 0x3F)].pack('C*')
              elsif c < 0x10000 then [0xE0 | (c >> 12), 0x80 | ((c >> 6) & 0x3F), 0x80 | (c & 0x3F)].pack('C*')
              else [0xF0 | (c >> 18), 0x80 | ((c >> 12) & 0x3F), 0x80 | ((c >> 6) & 0x3F), 0x80 | (c & 0x3F)].pack('C*') end)
      i += 1
    end
    out.force_encoding(Encoding::UTF_8)
  end

  def unseed(v)
    case v
    when Hash then v.keys == ['$utf16'] ? wtf8(v['$utf16']) : v.key?('$seed') && v.keys.all? { |k| %w[$seed es256 ec ed448].include?(k) } ? seed_member(v) : v.transform_values { |x| unseed(x) }
    when Array then v.map { |x| unseed(x) }
    else v
    end
  end

  def resolve_blobs(v, blobs)
    case v
    when Hash then v.size == 1 && v.key?('$blob') ? blobs.fetch(v['$blob']) : v.transform_values { |x| resolve_blobs(x, blobs) }
    when Array then v.map { |x| resolve_blobs(x, blobs) }
    else v
    end
  end

  def b64d(s) = Base64.urlsafe_decode64(s + ('=' * (-s.length % 4)))
  def b64e(b) = Base64.urlsafe_encode64(b, padding: false)

  # Oracle JSON -> Ruby: {"$bytes"} -> binary String.
  def dec(v)
    case v
    when Hash then v.size == 1 && v.key?('$bytes') ? b64d(v['$bytes']) : v.transform_values { |x| dec(x) }
    when Array then v.map { |x| dec(x) }
    else v
    end
  end

  # camelCase -> snake_case keys of one options Hash (top level only); anything else unchanged.
  def snake(h)
    return h unless h.is_a?(Hash)

    h.to_h { |k, v| [k.to_s.gsub(/([A-Z])/) { "_#{Regexp.last_match(1).downcase}" }, v] }
  end

  def norm(v)
    case v
    when Hash then v.to_h { |k, x| [k.to_s, norm(x)] }
    when Array then v.map { |x| norm(x) }
    when Symbol then v.to_s
    when Float
      return { '$num' => 'NaN' } if v.nan?
      return { '$num' => v.positive? ? 'Infinity' : '-Infinity' } if v.infinite?

      v == v.to_i && v.abs <= 2**64 ? v.to_i : v
    when String
      # bytes that are not UTF-8 text (a binary String, or a lone surrogate the JSON parser left as raw bytes) compare as bytes
      v.dup.force_encoding('UTF-8').valid_encoding? ? v : { '$bytes' => b64e(v) }
    else v
    end
  end

  def sort_keys(v)
    case v
    when Hash then v.keys.sort.to_h { |k| [k, sort_keys(v[k])] }
    when Array then v.map { |x| sort_keys(x) }
    else v
    end
  end

  def canon(v) = JSON.generate(sort_keys(norm(v)))
  def throws?(out) = out.is_a?(Hash) && out.key?('$throws')

  # Replay `cases` through call.(*args). A reference throw requires a native exception (same #code when the case has one)
  # or, with `refused`, a refusal value. `compare.(got, out, case)` overrides exact equality; `skip.(case)` -> reason skips.
  def run(test, cases, call, compare: nil, refused: nil, skip: nil, limit: 25)
    test.refute_nil cases, 'no cases for this fn in the corpus'
    bad = []
    ran = 0
    cases.each do |c|
      next if skip&.call(c)

      ran += 1
      out = c['out']
      begin
        got = call.call(*dec(c['args']))
      rescue StandardError => e
        if !throws?(out)
          bad << [c['name'], "raised #{e.class}: #{e.message}", out]
        elsif out.key?('code') && !(e.respond_to?(:code) && e.code == out['code'])
          bad << [c['name'], "raised code #{e.respond_to?(:code) ? e.code.inspect : 'none'}: #{e.message}", out]
        end
        next
      end
      if throws?(out)
        bad << [c['name'], "returned #{canon(got)[0, 300]}", out] unless refused&.call(got, c)
        next
      end
      eq = compare ? compare.call(got, out, c) : canon(got) == canon(out)
      unless eq
        g = canon(got)
        o = canon(out)
        i = (0...[g.length, o.length].min).find { |k| g[k] != o[k] } || [g.length, o.length].min
        from = [i - 120, 0].max # the window starts just before the first difference (long values share a long prefix)
        bad << [c['name'], "got #{from.positive? ? "...(differs at #{i}) " : ''}#{g[from, 400]}", o[from, 400]]
      end
    end
    test.assert bad.empty?, "#{bad.length} of #{ran} differ from the TS reference:\n" +
                            bad.first(limit).map { |n, g, o| "  #{n}\n    native: #{g}\n    ref:    #{o.to_s[0, 400]}" }.join("\n")
    ran
  end
end
