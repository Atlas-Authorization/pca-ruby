# frozen_string_literal: true

# Replays packages/pca/conformance/attestation-evidence-vectors.json (vendor hardware-attestation evidence: AMD SEV-SNP, Intel
# TDX DCAP, Azure MAA, GCP Confidential Space, NVIDIA GPU SPDM, plus the strict X.509 readers they share) through the native
# verifiers in atlas_pca/attest. Every row's `expect` was produced by RUNNING the TypeScript verifier, so a row passes only when
# the WHOLE result equals it (reason string byte for byte, except rows whose reason embeds an OpenSSL message: those compare the
# stable prefix). The file must exist: a missing file FAILS (it is generated and committed by the reference's CI).
#   ruby -Ilib test/test_attestation_vectors.rb        (PCA_CONFORMANCE_DIR overrides the corpus directory)
require_relative '../lib/atlas_pca'
require_relative '../lib/atlas_pca/attest'
require 'minitest/autorun'
require 'json'

class TestAttestationVectors < Minitest::Test
  NAME = 'attestation-evidence-vectors.json'

  def self.locate
    [ENV['PCA_CONFORMANCE_DIR'], File.expand_path('../conformance', __dir__),
     File.expand_path('../packages/pca/conformance', __dir__), File.expand_path('../conformance', __dir__)].compact.each do |d|
      path = File.join(d, NAME)
      return path if File.file?(path)
    end
    nil
  end

  PATH = locate
  DOC = PATH && JSON.parse(File.read(PATH, encoding: 'UTF-8'))
  # rows whose recorded outcome depends on optional TypeScript-side packages the reference's own run lacks on some hosts
  SKIP_IDS = (ENV['PCA_ATTEST_SKIP_IDS'] || '').split(',').freeze

  def self.hydrate(x, blobs)
    case x
    when Array then x.map { |e| hydrate(e, blobs) }
    when Hash then x.keys == ['$blob'] ? blobs.fetch(x['$blob']) : x.to_h { |k, v| [k, hydrate(v, blobs)] }
    else x
    end
  end

  # The whole result equals the expectation (prefix rows compare the stable reason prefix and everything else exactly).
  def same(got, want)
    want = want.dup
    if want.delete('reason_match') == 'prefix'
      prefix = want.delete('reason_prefix')
      reason = got['reason']
      return reason.is_a?(String) && reason.start_with?(prefix) && got.reject { |k, _| k == 'reason' } == want.reject { |k, _| k == 'reason' }
    end
    got == want
  end

  def setup
    flunk "conformance/#{NAME} is missing: it is generated by the reference and committed; this suite must not skip without it" if DOC.nil?
  end

  def test_documents_every_vendor
    assert_equal AtlasPca::Attest::VENDORS.sort, DOC['verifier_config_schema'].keys.sort
  end

  def test_coverage_and_intents
    rows = DOC['attestation_vectors']
    assert_equal rows.length, rows.map { |r| r['id'] }.uniq.length
    { 'amd-sev-snp' => 200, 'intel-tdx-dcap' => 250, 'azure-maa' => 150, 'gcp-confidential-space' => 88, 'nvidia-gpu-spdm' => 70 }.each do |vendor, min|
      of = rows.select { |r| r['vendor'] == vendor }
      assert_operator of.length, :>=, min, vendor
      assert(of.any? { |r| r['intent'] == 'accept' }, vendor)
      assert(of.any? { |r| r['intent'] == 'reject' }, vendor)
    end
    assert_operator DOC['x509_vectors'].length, :>=, 90
  end

  def test_every_attestation_row_answers_exactly_the_recorded_result
    only = ENV['PCA_ATTEST_VENDOR']
    bad = []
    n = 0
    DOC['attestation_vectors'].each do |r|
      next if SKIP_IDS.include?(r['id']) || (only && r['vendor'] != only)

      h = self.class.hydrate(r, DOC['blobs'])
      got = begin
        AtlasPca::Attest.run_attestation_vector(h)
      rescue StandardError, SystemStackError => e
        { 'THREW' => "#{e.class}: #{e.message}", 'at' => e.backtrace&.first }
      end
      n += 1
      bad << "#{r['id']}: got #{got.inspect[0, 400]} want #{h['expect'].inspect[0, 400]}" unless same(got, h['expect'])
    end
    warn "attestation rows run: #{n}, mismatches: #{bad.length}"
    assert_equal [], bad.first(25)
    assert_equal 0, bad.length
  end

  def test_every_x509_row_answers_exactly_the_recorded_result
    bad = DOC['x509_vectors'].filter_map do |r|
      got = AtlasPca::Attest.run_x509_vector(r['fn'], r['input'])
      "#{r['id']}: got #{got.inspect[0, 300]} want #{r['expect'].inspect[0, 300]}" unless got == r['expect']
    end
    assert_equal [], bad.first(25)
    assert_equal 0, bad.length
  end

  # strict profile: an SEV-SNP SVN claim of -0 (JSON -0.0) is not a non-negative integer, so a policy minimum refuses it
  def test_azure_sev_snp_svn_neg_zero_refused
    v = AtlasPca::Attest::AzureMaaVerifier.allocate
    v.instance_variable_set(:@has_sev, true)
    policy = { 'sevSnpMeasurements' => ['ab'], 'sevSnpMinTcb' => { 'tee' => 0 } }
    tee = { 'x-ms-sevsnpvm-launchmeasurement' => 'AB' }
    fail_with = ->(r) { { 'ok' => false, 'reason' => r } }
    assert v.send(:sev_result, policy, tee.merge('x-ms-sevsnpvm-tee-svn' => 0), fail_with)['ok']
    got = v.send(:sev_result, policy, tee.merge('x-ms-sevsnpvm-tee-svn' => -0.0), fail_with)
    assert_equal "SEV-SNP tee SVN claim 'x-ms-sevsnpvm-tee-svn' is missing or not a non-negative integer (policy requires a minimum)", got['reason']
  end
  def row(id, policy = {})
    h = Marshal.load(Marshal.dump(self.class.hydrate(DOC['attestation_vectors'].find { |x| x['id'] == id }, DOC['blobs'])))
    h['config']['policy'] = (h['config']['policy'] || {}).merge(policy)
    h
  end

  def run_row(r) = AtlasPca::Attest.run_attestation_vector(r)

  # attest-intel-collateral.test.ts 'reads the signed body': only the first member is signed, so a later duplicate changes nothing
  def test_intel_collateral_reads_the_signed_body_never_a_later_duplicate
    dup = lambda do |text, name|
      body = JSON.generate(JSON.parse(text)[name]).gsub('UpToDate', 'Revoked')
      t = text.sub(',"signature":', %(,"#{name}":#{body},"signature":))
      refute_equal JSON.parse(text)[name], JSON.parse(t)[name]
      t
    end
    honest = run_row(row('tdx-real-positive'))
    assert_equal true, honest['ok']
    { 'tcbInfoJson' => 'tcbInfo', 'qeIdentityJson' => 'enclaveIdentity' }.each do |k, name|
      r = row('tdx-real-positive')
      c = r['evidence']['collateral']
      c[k] = dup.call(c[k], name)
      assert_equal honest, run_row(r), name
    end
  end

  # the ARK pin comes from `family` alone: a configuration can not replace the root of trust
  def test_amd_ark_pin_is_not_configurable
    r = row('snp-syn-positive-report-data')
    assert_equal true, run_row(r)['ok']
    assert r['config'].key?('trustAnchorArkSpkiSha384')
    v = AtlasPca::Attest.verifier_from_config(r['vendor'], r['config'], ->(_doc) { r['evidence'] })
    got = v.verify({}, r['expected_binding'], r['now'])
    assert_equal false, got['ok']
    assert_includes got['reason'], 'ARK does not match the pinned AMD trust anchor'
  end

  # a malformed list is never "no list": one non-string entry denies, as the reference's .map(toLowerCase) throwing does
  def test_a_malformed_allowlist_denies
    [['snp-real-positive', 'hostData'], ['snp-real-positive', 'chipIds'], ['tdx-real-positive', 'fmspcs'], ['tdx-real-positive', 'rtmrs'],
     ['maa-real-sevsnp-positive', 'sevSnpHostData'], ['maa-real-tdx-positive', 'tdxRtmrs']].each do |id, key|
      assert_equal true, run_row(row(id))['ok'], id
      refute_equal true, run_row(row(id, key => ['aa', 1]))['ok'], "#{id} #{key}"
    end
    got = run_row(row('tdx-real-positive', 'collateral' => { 'acceptStatuses' => ['SWHardeningNeeded', 1] }))
    refute_equal true, got['ok']
  end

  # attest-intel-collateral.ts: `infoNum < minEval` coerces a numeric string. NaN would drop the floor there; here it refuses.
  def test_min_tcb_evaluation_data_number_as_a_string_keeps_its_floor
    run = ->(v) { run_row(row('tdx-real-positive', 'collateral' => { 'minTcbEvaluationDataNumber' => v })) }
    [1, '1', ' 1 ', 1.5].each { |v| assert_equal true, run.call(v)['ok'], v.inspect }
    [999_999, '999999', 'abc', '1e9', Float::NAN].each do |v|
      got = run.call(v)
      assert_equal false, got['ok'], v.inspect
      assert_includes got['reason'], 'tcbEvaluationDataNumber below policy minimum', v.inspect
    end
  end
end
