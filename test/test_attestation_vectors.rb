# frozen_string_literal: true

# Replays packages/pca/conformance/attestation-evidence-vectors.json (vendor hardware-attestation evidence: AMD SEV-SNP, Intel
# TDX DCAP, Azure MAA, GCP Confidential Space, NVIDIA GPU SPDM, plus the strict X.509 readers they share) through the native
# verifiers in atlas_pca/attest. Every row's `expect` was produced by RUNNING the TypeScript verifier, so a row passes only when
# the WHOLE result equals it (reason string byte for byte, except rows whose reason embeds an OpenSSL message: those compare the
# stable prefix). The file must exist: a missing file FAILS (it is generated and committed by the reference's CI).
#   ruby -Ilib test/test_attestation_vectors.rb        (PCA_CONFORMANCE_DIR overrides the corpus directory)
require_relative '../lib/atlas_pca'
require_relative '../lib/atlas_pca/attest'
require 'minitest/autorun'
require 'json'

class TestAttestationVectors < Minitest::Test
  NAME = 'attestation-evidence-vectors.json'

  def self.locate
    [ENV['PCA_CONFORMANCE_DIR'], File.expand_path('../conformance', __dir__),
     File.expand_path('../packages/pca/conformance', __dir__), File.expand_path('../conformance', __dir__)].compact.each do |d|
      path = File.join(d, NAME)
      return path if File.file?(path)
    end
    nil
  end

  PATH = locate
  DOC = PATH && JSON.parse(File.read(PATH, encoding: 'UTF-8'))
  # rows whose recorded outcome depends on optional TypeScript-side packages the reference's own run lacks on some hosts
  SKIP_IDS = (ENV['PCA_ATTEST_SKIP_IDS'] || '').split(',').freeze

  def self.hydrate(x, blobs)
    case x
    when Array then x.map { |e| hydrate(e, blobs) }
    when Hash then x.keys == ['$blob'] ? blobs.fetch(x['$blob']) : x.to_h { |k, v| [k, hydrate(v, blobs)] }
    else x
    end
  end

  # The whole result equals the expectation (prefix rows compare the stable reason prefix and everything else exactly).
  def same(got, want)
    want = want.dup
    if want.delete('reason_match') == 'prefix'
      prefix = want.delete('reason_prefix')
      reason = got['reason']
      return reason.is_a?(String) && reason.start_with?(prefix) && got.reject { |k, _| k == 'reason' } == want.reject { |k, _| k == 'reason' }
    end
    got == want
  end

  def setup
    flunk "conformance/#{NAME} is missing: it is generated by the reference and committed; this suite must not skip without it" if DOC.nil?
  end

  def test_documents_every_vendor
    assert_equal AtlasPca::Attest::VENDORS.sort, DOC['verifier_config_schema'].keys.sort
  end

  def test_coverage_and_intents
    rows = DOC['attestation_vectors']
    assert_equal rows.length, rows.map { |r| r['id'] }.uniq.length
    { 'amd-sev-snp' => 200, 'intel-tdx-dcap' => 250, 'azure-maa' => 150, 'gcp-confidential-space' => 88, 'nvidia-gpu-spdm' => 70 }.each do |vendor, min|
      of = rows.select { |r| r['vendor'] == vendor }
      assert_operator of.length, :>=, min, vendor
      assert(of.any? { |r| r['intent'] == 'accept' }, vendor)
      assert(of.any? { |r| r['intent'] == 'reject' }, vendor)
    end
    assert_operator DOC['x509_vectors'].length, :>=, 90
  end

  def test_every_attestation_row_answers_exactly_the_recorded_result
    only = ENV['PCA_ATTEST_VENDOR']
    bad = []
    n = 0
    DOC['attestation_vectors'].each do |r|
      next if SKIP_IDS.include?(r['id']) || (only && r['vendor'] != only)

      h = self.class.hydrate(r, DOC['blobs'])
      got = begin
        AtlasPca::Attest.run_attestation_vector(h)
      rescue StandardError, SystemStackError => e
        { 'THREW' => "#{e.class}: #{e.message}", 'at' => e.backtrace&.first }
      end
      n += 1
      bad << "#{r['id']}: got #{got.inspect[0, 400]} want #{h['expect'].inspect[0, 400]}" unless same(got, h['expect'])
    end
    warn "attestation rows run: #{n}, mismatches: #{bad.length}"
    assert_equal [], bad.first(25)
    assert_equal 0, bad.length
  end

  def test_every_x509_row_answers_exactly_the_recorded_result
    bad = DOC['x509_vectors'].filter_map do |r|
      got = AtlasPca::Attest.run_x509_vector(r['fn'], r['input'])
      "#{r['id']}: got #{got.inspect[0, 300]} want #{r['expect'].inspect[0, 300]}" unless got == r['expect']
    end
    assert_equal [], bad.first(25)
    assert_equal 0, bad.length
  end
end
